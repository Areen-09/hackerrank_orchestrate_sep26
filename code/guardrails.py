def validate_explanation_grounding(
    explanation: str,
    status: str,
    method: str,
    amount_safe: float,
    min_balance: float,
    currency: str
) -> str:
    """
    Asserts that the explanation text generated by the LLM aligns with the deterministic decision.
    If the LLM produced a hallucinated or contradictory statement, safely falls back to a grounded template.
    """
    if not explanation or not isinstance(explanation, str):
        return generate_fallback_explanation(status, method, amount_safe, min_balance, currency)

    lower = explanation.lower()

    # If not affordable, explanation must not say "pay in full today" or "fully affordable"
    if status == "not_affordable":
        if "affordable today" in lower or "pay in full today" in lower:
            return generate_fallback_explanation(status, method, amount_safe, min_balance, currency)

    # If affordable now, explanation should not say "cannot afford"
    if status == "affordable_now":
        if "cannot afford" in lower or "not affordable" in lower:
            return generate_fallback_explanation(status, method, amount_safe, min_balance, currency)

    return explanation.strip()


def generate_fallback_explanation(
    status: str,
    method: str,
    amount_safe: float,
    min_balance: float,
    currency: str
) -> str:
    """
    Fallback deterministic explanation if LLM fails or produces ungrounded output.
    """
    if status == "affordable_now":
        return f"Pay {currency} {amount_safe:,.2f} today. This keeps available balance above the {currency} {min_balance:,.2f} minimum over the next 90 days."
    elif status == "affordable_with_plan":
        return f"Proceed using {method}. This plan keeps the balance at or above the {currency} {min_balance:,.2f} minimum."
    elif status == "affordable_later":
        return f"Wait until the full amount becomes safe. Paying earlier would take the balance below the {currency} {min_balance:,.2f} minimum."
    else:
        return f"Do not proceed with this payment. None of the available options keeps the {currency} {min_balance:,.2f} minimum protected."
